test('no API keys / inference endpoints in PWA layer (no-API guarantee)', () => {
  for (const text of [sw, pwaJs, JSON.stringify(manifest)]) {
    for (const key of ['OPENAI_API_KEY', 'ANTHROPIC_API_KEY', 'GEMINI_API_KEY', 'MISTRAL_API_KEY']) {
      assert.ok(!text.includes(key), `PWA layer must not contain ${key}`);
    }
    for (const endpoint of ['api.openai.com', 'api.anthropic.com', 'api.mistral.ai', 'generativelanguage.googleapis.com']) {
      assert.ok(!text.includes(endpoint), `PWA layer must not reference ${endpoint}`);
    }
  }
});
