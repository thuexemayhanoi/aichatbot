test('drawer: one implementation for the Agent app and content pages', () => {
  assert.ok(!/body\.content-page \.motoai-drawer\s*\{/.test(read(CSS_SOURCE)), 'content pages reuse the shared drawer rules');
  assert.match(css, /\.motoai-drawer\s*\{[^}]*background:\s*var\(--surface\);[^}]*box-shadow:\s*var\(--shadow-2\);/s);
  assert.match(css, /\.motoai-drawer-backdrop\s*\{[^}]*background:\s*var\(--scrim\);/s);
  // v79: the panel slides with a transform TRANSITION driven by .is-open (no keyframes); reduced motion drops it.
  assert.match(css, /\.motoai-drawer\s*\{[^}]*transform:\s*translateX\(-100%\);[^}]*transition:\s*transform var\(--t3\)/s, 'closed panel sits off screen, slides on .is-open');
  assert.match(css, /\.motoai-drawer\.is-open\s*\{\s*transform:\s*none;\s*visibility:\s*visible;/);
  assert.ok(!/@keyframes drawer-in|\.motoai-drawer[^{]*\{[^}]*animation:/.test(css), 'no keyframe slide-in left on the panel');
  const reduced = /@media \(prefers-reduced-motion: reduce\) \{((?:[^{}]*\{[^}]*\})*)\s*\}/.exec(css)?.[1] ?? '';
  assert.match(reduced, /\.motoai-drawer,\s*\.motoai-drawer-backdrop\s*\{\s*transition:\s*none;\s*\}/, 'reduced motion: no slide-in');
  // Content pages only re-place the SAME element as a desktop column (>= 1200px); no second drawer skin.
  const blogSource = read(CSS_SOURCE);
  const start = blogSource.indexOf('/* ==================== Desktop layout (v79');
  const end = blogSource.indexOf('@media (min-width: 1200px) and (max-width: 1399.98px)', start);
  assert.ok(start > 0 && end > start, 'desktop layout block present');
  const panelRules = [...blogSource.matchAll(/^[^\n{}]*\.motoai-drawer\s*\{/gm)];
  assert.ok(panelRules.length > 0);
  for (const m of panelRules) {
    assert.ok(m.index > start && m.index < end, `drawer rule outside the desktop column block: ${m[0].trim()}`);
    assert.match(m[0], /body\.content-page > \.motoai-drawer \{$/, 'only the direct child of a content page becomes the column');
  }
});
