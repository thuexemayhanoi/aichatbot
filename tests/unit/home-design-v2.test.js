import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { chatTokenBlock, CSS_SOURCE, CHAT_CSS } from '../../tools/css-build.mjs';
import { BLOG_UI, brandMark, icon } from '../../tools/blog-components.mjs';
import { navigation, drawerCore } from '../../tools/taxonomy.mjs';
import { menuButton } from '../../tools/app-shell.mjs';

/**
 * v74 Apple-inspired editorial V2 on the chat app — ONE design source.
 * The Agent app (/agent/ since v76) loads only style.css, so its tokens, brand mark, icons and
 * theme-color are GENERATED by the build from the content-site sources:
 * editing assets/css/src/blog.css or config/blog-ui.json re-skins both.
 * v79: no bottom tab bar — the shared sidebar (renderDrawer) carries the glyphs and
 * ☰ Danh mục (menuButton) opens the Agent header row.
 */

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const read = (p) => readFileSync(join(ROOT, p), 'utf8');
const css = read(CHAT_CSS);
const html = read('agent/index.html');
// The Agent app's sidebar (renderDrawer({ mode: 'chat' })) and its header row.
const drawer = /<nav class="motoai-drawer"[^>]*>[\s\S]*?<\/nav>/.exec(html)?.[0] ?? '';
const header = /<header class="motoai-header">[\s\S]*?<\/header>/.exec(html)?.[0] ?? '';
const flat = (s) => s.replace(/\s+/g, ' ').trim();

test('chat tokens are the generated copy of the blog TOKENS (no drift)', () => {
  assert.ok(css.includes(chatTokenBlock(read(CSS_SOURCE))), 'style.css chat-tokens block is stale: run node tools/build-blog.mjs');
  const handwritten = css.slice(css.indexOf('/* @end chat-tokens */'));
  for (const token of ['--paper', '--surface', '--ink', '--line', '--signal', '--font', '--ease', '--color-bg', '--color-primary', '--color-text']) {
    assert.ok(!new RegExp(`${token}:`).test(handwritten), `${token} is defined only by the generated block`);
  }
});

test('chat token block fails loudly instead of emitting a missing token', () => {
  const source = read(CSS_SOURCE);
  assert.throws(() => chatTokenBlock(source.replace('--signal-ink: #0066cc;', '')), /signal-ink/);
  assert.throws(() => chatTokenBlock('.x { color: red; }'), /TOKENS/);
});

test('Agent app identity comes from the content-site sources: brand mark, icons, theme-color', () => {
  assert.ok(html.includes(`<div class="motoai-brand-mark" aria-hidden="true">${brandMark()}</div>`), 'same brand mark as every content page');
  assert.ok(drawer, 'the Agent app renders the shared sidebar');
  assert.ok(drawer.includes(`<a class="motoai-drawer-brand" href="/" aria-label="MotoAI — trang chủ">${brandMark()}<strong>MotoAI</strong></a>`), 'the sidebar head carries the same brand mark');
  // v79: the bottom tab bar is gone; its glyphs live in the sidebar — top links, groups and hubs — as inline SVG from the shared icon set.
  const svg = navigation.svg_icons;
  const glyphs = [svg.home, svg.agent, svg.search, ...Object.values(svg.groups), ...Object.values(svg.hubs)];
  for (const name of glyphs) {
    assert.ok(drawer.includes(icon(name, 'motoai-nav-icon')), `sidebar glyph ${name} from the shared icon set`);
  }
  assert.ok(drawer.includes(`aria-label="${BLOG_UI.labels.menuClose}" data-close="${BLOG_UI.labels.menuClose}" data-collapse="${BLOG_UI.labels.menuCollapseSidebar}">${icon('close', 'motoai-icon')}</button>`), 'the ✕ close icon keeps its accessible name');
  const allowed = new Set([brandMark(), icon('close', 'motoai-icon'), ...glyphs.map((name) => icon(name, 'motoai-nav-icon'))]);
  const drawn = [...drawer.matchAll(/<svg[\s\S]*?<\/svg>/g)].map((m) => m[0]);
  assert.ok(drawn.length >= allowed.size, 'every sidebar glyph is drawn');
  for (const s of drawn) assert.ok(allowed.has(s), `sidebar svg outside the shared icon set: ${s.slice(0, 60)}`);
  // drawerCore() still carries the legacy emoji, but the rendered rows never show it (only the theme / reset utilities keep theirs).
  const rows = drawer.replace(/<li class="motoai-drawer-util">[\s\S]*?<\/li>/g, '');
  const emoji = new Set();
  const collect = (items) => items.forEach((e) => { if (e.icon && /\p{Extended_Pictographic}/u.test(e.icon)) emoji.add(e.icon); collect(e.children ?? []); });
  collect(drawerCore());
  assert.ok(emoji.size > 0);
  for (const e of emoji) assert.ok(!rows.includes(e), `sidebar row renders emoji ${e}`);
  assert.ok(html.includes(`aria-label="Gửi câu hỏi">${icon('send', 'motoai-icon')}</button>`), 'send icon keeps its accessible name');
  const { light, dark } = BLOG_UI.site.themeColor;
  assert.ok(html.includes(`<meta name="theme-color" content="${light}" media="(prefers-color-scheme: light)">`));
  assert.ok(html.includes(`<meta name="theme-color" content="${dark}" media="(prefers-color-scheme: dark)">`));
  assert.equal(JSON.parse(read('manifest.webmanifest')).theme_color, light, 'installed app bar matches the page');
});

