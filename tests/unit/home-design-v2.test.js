test('iPhone: no sticky hover — every :hover lives in the fine-pointer media block', () => {
  const pointerOnly = /@media \(hover: hover\) and \(pointer: fine\)\s*\{(?:[^{}]*\{[^}]*\})*\s*\}/g;
  const rest = css.replace(/\/\*[\s\S]*?\*\//g, '').replace(pointerOnly, '');
  assert.ok(!/:hover/.test(rest), 'a :hover outside the pointer-only block stays stuck after a tap on iPhone');
});

test('header: identity row with the content-site controls; address on its own row', () => {
  // v79: ☰ Danh mục opens the identity row (owner spec: visible on every device), then mark · title · actions.
  assert.match(css, /\.motoai-header\s*\{[^}]*grid-template-areas:\s*"menu mark title actions" "sub sub sub sub" "status status status status";/s);
  assert.match(css, /@media \(min-width: 768px\) \{(?:[^{}]*\{[^}]*\})*?[^{}]*?(?:\n|\*\/)\s*\.motoai-header \{[^}]*grid-template-areas:\s*"menu mark title status actions" "menu mark sub status actions";/, 'tablet+: one identity row, ☰ first');
  assert.match(css, /\.motoai-menu\s*\{[^}]*grid-area:\s*menu;[^}]*min-height:\s*44px;/s, '☰ sits in the menu cell, 44px target');
  assert.ok(!/\.motoai-header \.motoai-menu\s*\{[^}]*display:\s*none/.test(css), 'the Agent header never hides ☰ (only the embed widget does)');
  assert.match(css, /\.motoai-status:empty\s*\{\s*display:\s*none;\s*\}/, 'no blank status row');
  // Markup order: ☰ · identity (mark, title, address) · status · desktop menu · actions (theme + install, no second menu).
  const outline = header.replace(/(<nav class="site-nav"[^>]*>)[\s\S]*?<\/nav>/, '$1</nav>'); // the desktop menu's own items aside
  const children = [...outline.matchAll(/^ {8}<(\w+)[^>]*? class="([^"]+)"/gm)].map((m) => `${m[1]}.${m[2]}`);
  assert.deepEqual(children, ['button.motoai-menu', 'div.motoai-header-text', 'span.motoai-status', 'nav.site-nav', 'div.motoai-header-actions']);
  assert.equal(flat(/<header class="motoai-header">\s*(<button[^>]*id="motoai-menu-btn"[\s\S]*?<\/button>)/.exec(header)?.[1] ?? ''), flat(menuButton()), '☰ is the shared menuButton(), first');
  assert.match(header, /<div class="motoai-header-text">\s*<div class="motoai-brand-mark" aria-hidden="true">[\s\S]*?<h1 class="motoai-title">[^<]+<\/h1>\s*<p class="motoai-subtitle" id="motoai-subtitle">/, 'identity: mark, title, address on its own row');
  const actions = /<div class="motoai-header-actions">([\s\S]*?)<\/div>/.exec(header)?.[1] ?? '';
  assert.match(actions, /^\s*<button[^>]*id="blog-theme-toggle"[^>]*>[^<]*<\/button>\s*<button[^>]*id="motoai-install"[^>]*>[^<]*<\/button>\s*$/, 'actions: theme toggle then install, nothing else');
  assert.ok(!actions.includes('motoai-menu'), 'no second menu control in the actions');
  assert.equal((html.match(/id="motoai-menu-btn"/g) ?? []).length, 1, 'exactly one ☰ Danh mục');
  assert.match(css, /\.motoai-theme\s*\{[^}]*min-height:\s*44px;[^}]*min-width:\s*44px;/s);
});

